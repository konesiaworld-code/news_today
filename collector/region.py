KOREA = re.compile("|".join(_KOREA))
FOREIGN = re.compile("|".join(_FOREIGN))


def _verdict(text: str) -> bool | None:
    """한국 관련이면 True, 다른 나라 소식이면 False, 판단할 말이 없으면 None."""
    # 기사 제목의 한자는 '호환용 한자'(李 = U+F9E1)로 오는 경우가 많아 표준 글자로 바꿉니다.
    text = unicodedata.normalize("NFKC", text)
    if KOREA.search(text):
        return True
    if FOREIGN.search(text):
        return False
    return None


def is_korea_related(title: str, desc: str = "") -> bool:
    """국내 피드에서 온 기사가 한국 관련 소식인지 판단합니다."""
    v = _verdict(title)
    if v is None:
        v = _verdict(desc[:150])
    return v is not False
